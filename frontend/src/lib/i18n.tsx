interface I18nContextValue {
  language: Language
  direction: 'rtl' | 'ltr'
  setLanguage: (language: Language) => void
  toggleLanguage: () => void
  t: (text: string) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      return window.localStorage.getItem('barber-house-language') === 'en' ? 'en' : 'ar'
    } catch {
      return 'ar'
    }
  })

  const setLanguage = (next: Language) => {
    setLanguageState(next)
    try {
      window.localStorage.setItem('barber-house-language', next)
    } catch {
      // Keep the current selection for this session if storage is unavailable.
    }
  }

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr'
  }, [language])

  const value = useMemo<I18nContextValue>(() => ({
    language,
    direction: language === 'ar' ? 'rtl' : 'ltr',
    setLanguage,
    toggleLanguage: () => setLanguage(language === 'ar' ? 'en' : 'ar'),
    t: (text) => language === 'ar' ? text : translations[text] ?? text,
  }), [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used within I18nProvider')
  return context
}
